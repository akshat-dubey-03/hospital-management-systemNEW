-- DBMS Review 3 — index optimisation (evidence: docs/dbms/indexing.md).
--
-- The patient dashboard runs
--   SELECT ... FROM appointments WHERE "patientId" = $1
--   ORDER BY "appointmentDate", "startTime";
-- With only a single-column patientId index PostgreSQL fetches the rows and
-- then sorts them. A composite (patientId, appointmentDate, startTime) index
-- returns them already in order. Its leftmost column still serves every plain
-- "patientId = $1" lookup (including the FK check when a patient is deleted),
-- so the single-column index becomes redundant and is dropped.
-- DDL generated by `prisma migrate diff` from schema.prisma; the CREATE runs
-- before the DROP so patientId lookups are never left without an index.

-- CreateIndex
CREATE INDEX "appointments_patientId_appointmentDate_startTime_idx" ON "appointments"("patientId", "appointmentDate", "startTime");

-- DropIndex
DROP INDEX "appointments_patientId_idx";
